import asyncio
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional
import uuid

logger = logging.getLogger(__name__)

DOCS_DIR = Path("data/office_documents")
DOCS_DIR.mkdir(parents=True, exist_ok=True)

class DocumentTool:
    """
    Creates and edits professional Word documents (.docx) and extracts text from PDFs.
    """
    def __init__(self):
        self.output_dir = DOCS_DIR

    async def create_word_document(
        self,
        title: str,
        sections: Optional[Dict[str, str]] = None,
        author: str = "OpenTab AI"
    ) -> Path:
        """
        Generates a styled Word (.docx) document.
        """
        fn = f"document_{uuid.uuid4().hex[:8]}.docx"
        out_path = self.output_dir / fn

        def _build_docx():
            try:
                from docx import Document
                from docx.shared import Inches, Pt, RGBColor
                from docx.enum.text import WD_ALIGN_PARAGRAPH

                doc = Document()

                # Document Title
                t_p = doc.add_paragraph()
                t_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = t_p.add_run(title)
                run.font.size = Pt(26)
                run.font.bold = True
                run.font.color.rgb = RGBColor(30, 41, 59)

                # Subtitle / Author
                s_p = doc.add_paragraph()
                s_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                s_run = s_p.add_run(f"Prepared by {author} • Autonomous Document Engine")
                s_run.font.size = Pt(11)
                s_run.font.italic = True
                s_run.font.color.rgb = RGBColor(100, 116, 139)

                doc.add_paragraph() # Spacer

                default_sections = sections or {
                    "1. Executive Overview": (
                        "This document outlines strategic architectural principles and actionable "
                        "deliverables designed for autonomous, multi-modal systems."
                    ),
                    "2. Technical Architecture": (
                        "OpenTab operates on an execution-first paradigm. Every instruction is decomposed "
                        "into a verifiable DAG, selecting specialist engines across Image, Video, Office, "
                        "and Coding domains."
                    ),
                    "3. Key Deliverables & Milestones": (
                        "• Direct Turn-1 Execution with zero conversational stalls.\n"
                        "• Multi-format media and document delivery directly over Telegram.\n"
                        "• Persistent 7-layer memory retaining project preferences."
                    ),
                    "4. Conclusion & Next Steps": (
                        "The platform continues to expand capabilities across mobile compilation (APK), "
                        "presentation design, and multilingual AI reading."
                    )
                }

                for sec_title, sec_body in default_sections.items():
                    h = doc.add_heading(sec_title, level=1)
                    h.paragraph_format.space_before = Pt(14)
                    h.paragraph_format.space_after = Pt(6)

                    p = doc.add_paragraph(sec_body)
                    p.paragraph_format.line_spacing = 1.25
                    p.paragraph_format.space_after = Pt(10)

                doc.save(str(out_path))
                logger.info(f"Word document generated: {out_path}")
                return out_path
            except Exception as e:
                logger.error(f"Docx creation error ({e}), writing markdown fallback.")
                md_path = out_path.with_suffix(".md")
                md_path.write_text(f"# {title}\n\nDocument generated by OpenTab.", encoding="utf-8")
                return md_path

        return await asyncio.to_thread(_build_docx)

    async def extract_document_text(self, file_path: Path) -> Dict[str, Any]:
        """
        Universal text extractor supporting PDF, DOCX, PPTX, TXT.
        """
        p = Path(file_path)
        if not p.exists():
            return {"error": f"File not found: {p}"}

        ext = p.suffix.lower()

        def _extract():
            text_parts = []
            page_count = 1

            if ext == ".pdf":
                try:
                    import pypdf
                    reader = pypdf.PdfReader(str(p))
                    page_count = len(reader.pages)
                    for i, page in enumerate(reader.pages):
                        t = page.extract_text() or ""
                        if t.strip():
                            text_parts.append(f"--- Page {i+1} ---\n{t.strip()}")
                except Exception as ex:
                    logger.warning(f"pypdf extraction failed ({ex})")

            elif ext == ".docx":
                try:
                    import docx
                    doc = docx.Document(str(p))
                    for para in doc.paragraphs:
                        if para.text.strip():
                            text_parts.append(para.text.strip())
                except Exception as ex:
                    logger.warning(f"docx extraction failed ({ex})")

            elif ext == ".pptx":
                try:
                    from pptx import Presentation
                    prs = Presentation(str(p))
                    page_count = len(prs.slides)
                    for i, slide in enumerate(prs.slides):
                        slide_texts = []
                        for shape in slide.shapes:
                            if shape.has_text_frame:
                                for para in shape.text_frame.paragraphs:
                                    if para.text.strip():
                                        slide_texts.append(para.text.strip())
                        if slide_texts:
                            text_parts.append(f"--- Slide {i+1} ---\n" + "\n".join(slide_texts))
                except Exception as ex:
                    logger.warning(f"pptx extraction failed ({ex})")

            else:
                # Plain text / fallback
                try:
                    text_parts.append(p.read_text(encoding="utf-8", errors="ignore"))
                except Exception:
                    pass

            full_text = "\n\n".join(text_parts).strip()
            return {
                "file_name": p.name,
                "extension": ext,
                "page_count": page_count,
                "character_count": len(full_text),
                "text": full_text
            }

        return await asyncio.to_thread(_extract)

document_tool = DocumentTool()
